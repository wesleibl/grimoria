CREATE TABLE IF NOT EXISTS usuarios (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(80) NOT NULL,
  email VARCHAR(190) NOT NULL,
  senha_hash VARCHAR(255) NOT NULL,
  papel ENUM('jogador', 'mestre') NOT NULL DEFAULT 'jogador',
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS estado (
  chave VARCHAR(64) NOT NULL PRIMARY KEY,
  valor MEDIUMTEXT NOT NULL,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS jogadores (
  id VARCHAR(40) NOT NULL PRIMARY KEY,
  dados MEDIUMTEXT NOT NULL,
  usuario_id INT UNSIGNED NULL,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_usuario (usuario_id),
  CONSTRAINT fk_jog_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS imagens (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  tipo ENUM('avatar', 'mapa', 'local') NOT NULL,
  ref VARCHAR(64) NOT NULL DEFAULT '',
  titulo VARCHAR(120) NOT NULL DEFAULT '',
  mime VARCHAR(40) NOT NULL,
  dados MEDIUMBLOB NOT NULL,
  liberado TINYINT(1) NOT NULL DEFAULT 0,
  criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY ix_tipo_ref (tipo, ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4
